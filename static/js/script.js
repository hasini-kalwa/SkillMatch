
const assessmentForm = document.getElementById("assessmentForm");
const analyzeButton = document.getElementById("analyzeButton");
const buttonText = document.getElementById("buttonText");
const formError = document.getElementById("formError");

const resultsSection = document.getElementById("results");
const metricsContainer = document.getElementById("metricsContainer");
const resetButton = document.getElementById("resetButton");

const fields = {
    skills_score: document.getElementById("skills"),
    projects: document.getElementById("projects"),
    coding_hours: document.getElementById("hours"),
    cs_score: document.getElementById("cs"),
    communication: document.getElementById("communication")
};

// Validate the submitted values.
function getCandidateData() {
    const candidate = {};

    for (const [key, input] of Object.entries(fields)) {
        const value = input.value.trim();
        const number = Number(value);
        const label = input.labels?.[0]?.textContent.trim() || key;

        if (value === "" || !Number.isFinite(number)) {
            throw new Error(`Please enter a valid value for ${label}.`);
        }

        const min = Number(input.min);
        const max = Number(input.max);

        if (number < min || number > max) {
            throw new Error(`${label} must be between ${min} and ${max}.`);
        }

        if (key === "projects" && !Number.isInteger(number)) {
            throw new Error("Projects completed must be a whole number.");
        }

        candidate[key] = number;
    }

    return candidate;
}

function showError(message) {
    formError.textContent = message;
    formError.hidden = false;
}

function clearError() {
    formError.textContent = "";
    formError.hidden = true;
}

// Display each model's prediction.
function displayPrediction(elementId, prediction) {
    const element = document.getElementById(elementId);

    element.textContent = prediction;
    element.classList.remove("ready", "needs-preparation");

    if (prediction === "Ready") {
        element.classList.add("ready");
    } else if (prediction === "Needs Preparation") {
        element.classList.add("needs-preparation");
    }
}

// Show the candidate's submitted profile.
function renderProfile(candidate) {
    document.getElementById("profileSkills").textContent =
        `${candidate.skills_score}/100`;

    document.getElementById("profileProjects").textContent =
        candidate.projects;

    document.getElementById("profileHours").textContent =
        `${candidate.coding_hours} hrs/week`;

    document.getElementById("profileCS").textContent =
        `${candidate.cs_score}/100`;

    document.getElementById("profileCommunication").textContent =
        `${candidate.communication}/100`;
}

// Give an overall verdict based on both model predictions.
function renderReadiness(logistic, forest) {
    const verdict = document.getElementById("readinessVerdict");
    const explanation = document.getElementById("readinessExplanation");
    const summary = document.getElementById("readinessSummary");

    summary.classList.remove("verdict-ready", "verdict-preparation", "verdict-mixed");

    if (logistic === forest && logistic === "Ready") {
        verdict.textContent = "Ready to Apply";
        explanation.textContent =
            "Both models classify your profile as Ready. Use this as a starting point for your internship preparation, not as a guarantee of selection.";
        summary.classList.add("verdict-ready");
    } else if (
        logistic === forest &&
        logistic === "Needs Preparation"
    ) {
        verdict.textContent = "More Preparation Recommended";
        explanation.textContent =
            "Both models classify your profile as Needs Preparation. Review your profile and focus on strengthening your skills before your next applications.";
        summary.classList.add("verdict-preparation");
    } else {
        verdict.textContent = "Mixed Prediction";
        explanation.textContent =
            "The models disagree about your readiness. Treat this as an uncertain result and review your profile rather than relying on one prediction.";
        summary.classList.add("verdict-mixed");
    }
}

// Suggestions are based on input values, not generated by the ML models.
function renderSuggestions(candidate) {
    const list = document.getElementById("improvementList");
    list.replaceChildren();

    const suggestions = [];

    if (candidate.skills_score < 70) {
        suggestions.push(
            "Strengthen your role-related skills through focused practice."
        );
    }

    if (candidate.projects < 2) {
        suggestions.push(
            "Build and document at least two meaningful projects that you can explain in interviews."
        );
    }

    if (candidate.coding_hours < 5) {
        suggestions.push(
            "Set aside regular weekly time for coding practice and problem-solving."
        );
    }

    if (candidate.cs_score < 70) {
        suggestions.push(
            "Revise core computer science subjects such as DBMS, operating systems, and computer networks."
        );
    }

    if (candidate.communication < 70) {
        suggestions.push(
            "Practise explaining your projects aloud and answering common interview questions."
        );
    }

    if (suggestions.length === 0) {
        suggestions.push(
            "Keep practising, refine your projects, and prepare to explain your technical decisions in interviews."
        );
    }

    for (const suggestion of suggestions) {
        const item = document.createElement("li");
        item.textContent = suggestion;
        list.appendChild(item);
    }
}

// Render model evaluation metrics.
function renderMetrics(metrics) {
    const metricNames = [
        ["accuracy", "Accuracy"],
        ["precision", "Precision"],
        ["recall", "Recall"]
    ];

    const models = [
        {
            key: "Logistic Regression",
            label: "Logistic Regression",
            className: ""
        },
        {
            key: "Random Forest",
            label: "Random Forest",
            className: "forest-fill"
        }
    ];

    metricsContainer.replaceChildren();

    for (const [metricKey, metricLabel] of metricNames) {
        const row = document.createElement("div");
        row.className = "metric-row";

        const name = document.createElement("div");
        name.className = "metric-name";
        name.textContent = metricLabel;

        const bars = document.createElement("div");
        bars.className = "metric-bars";

        for (const model of models) {
            const value = metrics[model.key]?.[metricKey];

            if (
                typeof value !== "number" ||
                !Number.isFinite(value) ||
                value < 0 ||
                value > 1
            ) {
                throw new Error("Model evaluation metrics are missing or invalid.");
            }

            const percentage = value * 100;

            const line = document.createElement("div");
            line.className = "metric-bar-line";

            const modelName = document.createElement("span");
            modelName.className = "metric-model-name";
            modelName.textContent = model.label;

            const track = document.createElement("div");
            track.className = "metric-track";

            const fill = document.createElement("div");
            fill.className = `metric-fill ${model.className}`;
            fill.style.width = `${percentage}%`;

            track.appendChild(fill);

            const valueLabel = document.createElement("span");
            valueLabel.className = "metric-value";
            valueLabel.textContent = `${percentage.toFixed(1)}%`;

            line.append(modelName, track, valueLabel);
            bars.appendChild(line);
        }

        row.append(name, bars);
        metricsContainer.appendChild(row);
    }
}

assessmentForm.addEventListener("submit", async (event) => {
    event.preventDefault();
    clearError();

    let candidate;

    try {
        candidate = getCandidateData();
    } catch (error) {
        showError(error.message);
        return;
    }

    analyzeButton.disabled = true;
    buttonText.textContent = "Analyzing profile...";

    try {
        const response = await fetch("/predict", {
            method: "POST",
            headers: {
                "Content-Type": "application/json"
            },
            body: JSON.stringify(candidate)
        });

        const data = await response.json();

        if (!response.ok) {
            throw new Error(data.error || "Unable to analyze your profile.");
        }

        renderProfile(candidate);

        displayPrediction("logisticResult", data.logistic);
        displayPrediction("forestResult", data.forest);

        renderReadiness(data.logistic, data.forest);
        renderSuggestions(candidate);

        if (data.metrics) {
            renderMetrics(data.metrics);
        } else {
            metricsContainer.replaceChildren();

            const message = document.createElement("p");
            message.className = "metrics-placeholder";
            message.textContent =
                "Model evaluation metrics have not been connected yet.";

            metricsContainer.appendChild(message);
        }

        resultsSection.hidden = false;

        resultsSection.scrollIntoView({
            behavior: "smooth",
            block: "start"
        });
    } catch (error) {
        showError(
            error.message === "Failed to fetch"
                ? "Cannot connect to the server. Make sure the Flask application is running."
                : error.message || "Something went wrong. Please try again."
        );
    } finally {
        analyzeButton.disabled = false;
        buttonText.textContent = "Analyze my readiness";
    }
});

resetButton.addEventListener("click", () => {
    resultsSection.hidden = true;
    clearError();

    document.getElementById("assessment").scrollIntoView({
        behavior: "smooth",
        block: "start"
    });
});
